//! End-to-end tests for `pleamar-themes`: a theme file becomes `theme.plm`.
//!
//! Every case gets a throwaway HOME/XDG tree under `$TMPDIR`; nothing touches
//! the developer's real `~/.config`, and no wallpaper is sampled.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

const BIN: &str = env!("CARGO_BIN_EXE_pleamar-themes");

static SEQUENCE: AtomicU64 = AtomicU64::new(0);

struct Case {
    root: PathBuf,
}

impl Case {
    fn new(label: &str) -> Self {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or(0);
        let sequence = SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!(
            "pleamar-themes-test-{label}-{}-{nanos}-{sequence}",
            std::process::id()
        ));
        fs::create_dir_all(root.join("config/pleamar/themes")).expect("themes directory");
        fs::create_dir_all(root.join("home")).expect("home");
        Self { root }
    }

    fn config(&self) -> PathBuf {
        self.root.join("config")
    }

    fn themes(&self) -> PathBuf {
        self.config().join("pleamar/themes")
    }

    fn output(&self) -> PathBuf {
        self.config().join("pleamar/theme.plm")
    }

    fn theme(&self, name: &str, body: &str) -> PathBuf {
        let path = self.themes().join(format!("{name}.toml"));
        fs::write(&path, body).expect("write a theme file");
        path
    }

    fn run(&self, args: &[&str]) -> Output {
        Command::new(BIN)
            .args(args)
            .env("HOME", self.root.join("home"))
            .env("XDG_CONFIG_HOME", self.config())
            .output()
            .expect("run pleamar-themes")
    }
}

impl Drop for Case {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).expect("read the generated file")
}

#[test]
fn apply_writes_the_pipeline_s_skin_library() {
    let case = Case::new("apply");
    case.theme(
        "retro",
        "\
name = \"Retro\"
font = \"Iosevka\"
corner_rounding = 18
light = true

[palette]
coal = \"#101418\"
accent = \"#06C\"
",
    );
    let output = case.run(&["apply", "retro"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    let out = stdout(&output);
    assert!(out.contains("pleamar-themes: wrote "), "{out}");
    assert!(out.contains("pleamar-themes: theme Retro"), "{out}");

    let text = read(&case.output());
    assert!(
        text.starts_with("// theme.plm — the theme file's palette, generated by\n"),
        "{text}"
    );
    assert!(text.contains("// pleamar-themes from "), "{text}");
    assert!(text.contains("retro.toml"), "{text}");
    assert!(
        text.contains("// mode:    light (the theme file says so)"),
        "{text}"
    );
    assert!(text.contains("library Skin strict {"), "{text}");
    assert!(text.contains("let skin.coal = #101418"), "{text}");
    assert!(text.contains("let skin.accent = #0066cc"), "{text}");
    assert!(text.contains("let skin.light = true"), "{text}");
    // The keys this file left out keep the stock palette.
    assert!(text.contains("let skin.surface = #242A35"), "{text}");
    assert!(text.contains("let skin.ink.dim = #AEB9C8"), "{text}");

    let mode = fs::metadata(case.output())
        .expect("theme.plm metadata")
        .permissions()
        .mode()
        & 0o777;
    assert_eq!(mode, 0o644, "theme.plm is 0644 like the pipeline's");
}

#[test]
fn show_prints_the_file_without_writing_it() {
    let case = Case::new("show");
    case.theme("plain", "name = \"Plain\"\n");
    let output = case.run(&["show", "plain"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    assert!(stdout(&output).contains("library Skin strict {"));
    assert!(!case.output().exists(), "show writes nothing");
}

#[test]
fn a_path_is_read_as_given() {
    let case = Case::new("path");
    let path = case.theme("direct", "[palette]\nink = \"#ffffff\"\n");
    let output = case.run(&["apply", path.to_str().expect("utf-8 path")]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    assert!(read(&case.output()).contains("let skin.ink = #ffffff"));
}

#[test]
fn a_broken_file_is_named_with_its_line_and_leaves_theme_plm_alone() {
    let case = Case::new("broken");
    fs::write(case.output(), "sentinel\n").expect("sentinel");
    case.theme("broken", "name = \"Broken\"\n[palette]\nink = \"white\"\n");
    let output = case.run(&["apply", "broken"]);
    assert_eq!(output.status.code(), Some(1), "stdout: {}", stdout(&output));
    let error = stderr(&output);
    assert!(error.contains("broken.toml"), "{error}");
    assert!(error.contains("line 3:"), "{error}");
    assert!(error.contains("is not a hex colour"), "{error}");
    assert_eq!(read(&case.output()), "sentinel\n");
}

#[test]
fn list_names_the_good_themes_and_reports_the_broken_one() {
    let case = Case::new("list");
    case.theme(
        "retro",
        "name = \"Retro\"\nfont = \"Iosevka\"\ncorner_rounding = 18\n",
    );
    case.theme("bad", "unknown = 1\n");
    let output = case.run(&["list"]);
    assert_eq!(output.status.code(), Some(1), "stdout: {}", stdout(&output));
    let out = stdout(&output);
    assert!(out.contains("NAME"), "{out}");
    assert!(out.contains("Retro"), "{out}");
    assert!(out.contains("Iosevka"), "{out}");
    assert!(out.contains("18"), "{out}");
    assert!(!out.contains("bad"), "the broken theme is left out: {out}");
    let error = stderr(&output);
    assert!(error.contains("bad.toml"), "{error}");
    assert!(error.contains("line 1:"), "{error}");
}

#[test]
fn an_empty_directory_says_so() {
    let case = Case::new("empty");
    let output = case.run(&["list"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    assert!(
        stdout(&output).contains("no themes in "),
        "{}",
        stdout(&output)
    );
}

#[test]
fn a_missing_theme_is_reported() {
    let case = Case::new("missing");
    let output = case.run(&["apply", "nope"]);
    assert_eq!(output.status.code(), Some(1));
    assert!(
        stderr(&output).contains("cannot read"),
        "{}",
        stderr(&output)
    );
    assert!(!case.output().exists());
}

#[test]
fn a_usage_error_exits_two() {
    let case = Case::new("usage");
    let output = case.run(&["paint"]);
    assert_eq!(output.status.code(), Some(2));
    assert!(stderr(&output).contains("unknown command 'paint'"));
    let output = case.run(&[]);
    assert_eq!(output.status.code(), Some(2));
    assert!(stderr(&output).contains("no command"));
}

#[test]
fn plain_lists_one_row_per_theme_and_marks_the_applied_one() {
    let case = Case::new("plain");
    case.theme(
        "amber",
        "name = \"Amber\"\nfont = \"Iosevka\"\n[palette]\naccent = \"#ffb347\"\n",
    );
    case.theme(
        "cool",
        "name = \"Cool\"\ncorner_rounding = 12\n[palette]\naccent = \"#006fcc\"\n",
    );
    let output = case.run(&["apply", "amber"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));

    let output = case.run(&["list", "--plain"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    let text = stdout(&output);
    let lines: Vec<&str> = text.lines().collect();
    assert_eq!(lines.len(), 2, "{text}");

    let amber = lines
        .iter()
        .find(|line| line.contains("Amber"))
        .expect("the amber row");
    let fields: Vec<&str> = amber.split('\t').collect();
    assert_eq!(fields.len(), 5, "{amber}");
    assert_eq!(fields[0], "Amber");
    assert_eq!(fields[1], "Iosevka");
    assert_eq!(fields[2], "-");
    assert!(fields[3].ends_with("amber.toml"), "{amber}");
    assert_eq!(fields[4], "1", "the applied theme is marked: {amber}");

    let cool = lines
        .iter()
        .find(|line| line.contains("Cool"))
        .expect("the cool row");
    assert_eq!(cool.split('\t').nth(4), Some("0"), "{cool}");

    // Applying the other theme moves the mark.
    let output = case.run(&["apply", "cool"]);
    assert_eq!(output.status.code(), Some(0), "stderr: {}", stderr(&output));
    let text = stdout(&case.run(&["list", "--plain"]));
    for line in text.lines() {
        let selected = line.split('\t').nth(4).expect("five columns");
        if line.contains("Cool") {
            assert_eq!(selected, "1", "{line}");
        } else {
            assert_eq!(selected, "0", "{line}");
        }
    }
}
