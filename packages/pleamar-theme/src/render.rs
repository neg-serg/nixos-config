//! The generated `theme.plm` file.
//!
//! Everything here is the shell `render()` function: the same header comments,
//! the same blank lines, the same note above each `let`, and the same values.
//! The file is written to a temporary file in the destination directory and
//! renamed over the old one by the binary's writer; this module only
//! builds the bytes.

/// A resolved palette plus the provenance notes that go above each `let`.
#[derive(Clone, Debug)]
pub struct Theme {
    /// The wallpaper path, or `None` for the explicit-colour fallback.
    pub source: Option<String>,
    /// `"light"` or `"dark"`.
    pub mode: &'static str,
    /// What decided the mode, for the `// mode:` line.
    pub mode_note: String,
    pub coal_note: String,
    pub surface_note: String,
    pub ink_note: String,
    pub accent_note: String,
    pub coal: String,
    pub surface: String,
    pub ink: String,
    pub ink_dim: String,
    pub accent: String,
    /// `skin.light` is the mode, not the wallpaper's raw luminance.
    pub light: bool,
}

impl Theme {
    /// The complete file contents, byte for byte as `theme.sh` printed them.
    pub fn render(&self, written: &str) -> String {
        let source = self
            .source
            .as_deref()
            .unwrap_or("none (explicit colours only)");
        let mut text = String::with_capacity(4096);
        text.push_str("// theme.plm — the wallpaper palette, generated by\n");
        text.push_str("// files/pleamar/scripts/theme/theme.sh. Edits here are overwritten.\n");
        text.push_str("//\n");
        text.push_str(&format!("// source:  {source}\n"));
        text.push_str(&format!("// written: {written}\n"));
        text.push_str(&format!("// mode:    {} ({})\n", self.mode, self.mode_note));
        text.push_str("//\n");
        text.push_str(
            "// Import it after the palette (INTERFACES.md §1.4) and read skin.* names:\n",
        );
        text.push_str("//\n");
        text.push_str("//   import \"../../lib/palette.plm\"\n");
        text.push_str("//   import \"../../theme.plm\"\n");
        text.push_str("//\n");
        text.push_str(
            "// It declares no name palette.plm declares, so nothing in the shell changes\n",
        );
        text.push_str(
            "// meaning when a scene opts in; a rewritten import re-themes a running scene.\n",
        );
        text.push('\n');
        text.push_str("library Skin strict {\n");
        text.push('\n');
        text.push_str(&format!("    // {}\n", self.coal_note));
        text.push_str(&format!("    let skin.coal = {}\n", self.coal));
        text.push('\n');
        text.push_str(&format!("    // {}\n", self.surface_note));
        text.push_str(&format!("    let skin.surface = {}\n", self.surface));
        text.push('\n');
        text.push_str(&format!("    // {}\n", self.ink_note));
        text.push_str(&format!("    let skin.ink = {}\n", self.ink));
        text.push('\n');
        text.push_str(
            "    // colors.text.secondary (Settings/colors.jsonc) in the dark theme, its own dark tone\n",
        );
        text.push_str("    // in the light one — not a mix of the two sampled tones.\n");
        text.push_str(&format!("    let skin.ink.dim = {}\n", self.ink_dim));
        text.push('\n');
        text.push_str(&format!("    // {}\n", self.accent_note));
        text.push_str(&format!("    let skin.accent = {}\n", self.accent));
        text.push_str("    // Theme.accentHover: towardsWhite(accentPrimary, 0.2).\n");
        text.push_str("    let skin.accent.hover = mix(skin.accent, #ffffff, 20%)\n");
        text.push_str("    // Theme.accentDarkStrong: towardsBlack(accentPrimary, 0.8).\n");
        text.push_str("    let skin.accent.deep = mix(skin.accent, skin.coal, 80%)\n");
        text.push_str("    // colors.onAccent, unchanged.\n");
        text.push_str("    let skin.on.accent = #ffffff\n");
        text.push('\n');
        text.push_str(
            "    // Is the theme light? True when this palette is the light one — the wallpaper is\n",
        );
        text.push_str(
            "    // light on its mean WCAG luminance (the same 0.5 the reference uses), or\n",
        );
        text.push_str(
            "    // --mode/~/.config/pleamar/theme.mode forced it. A scene reads it to pick the part\n",
        );
        text.push_str(
            "    // of a design that only one theme has, never to patch the ink: the ink is here.\n",
        );
        text.push_str(&format!(
            "    let skin.light = {}\n",
            if self.light { "true" } else { "false" }
        ));
        text.push_str("}\n");
        text
    }
}

#[cfg(test)]
mod tests {
    use super::Theme;

    fn fallback_theme() -> Theme {
        Theme {
            source: None,
            mode: "dark",
            mode_note: "auto: the wallpaper is dark".to_string(),
            coal_note:
                "colors.background, the QS fallback #ff000000 (opaque part): no wallpaper was sampled."
                    .to_string(),
            surface_note:
                "colors.surfaceVariant, the QS fallback #242A35: no wallpaper was sampled."
                    .to_string(),
            ink_note: "colors.text.primary, the QS fallback #CBD6E5: no wallpaper was sampled."
                .to_string(),
            accent_note: "colors.accent.primary, the QS fallback #006FCC: no wallpaper was sampled."
                .to_string(),
            coal: "#000000".to_string(),
            surface: "#242A35".to_string(),
            ink: "#CBD6E5".to_string(),
            ink_dim: "#AEB9C8".to_string(),
            accent: "#006FCC".to_string(),
            light: false,
        }
    }

    #[test]
    fn the_fallback_file_is_byte_exact() {
        let expected = "\
// theme.plm — the wallpaper palette, generated by
// files/pleamar/scripts/theme/theme.sh. Edits here are overwritten.
//
// source:  none (explicit colours only)
// written: 2026-11-02T21:27:41Z
// mode:    dark (auto: the wallpaper is dark)
//
// Import it after the palette (INTERFACES.md §1.4) and read skin.* names:
//
//   import \"../../lib/palette.plm\"
//   import \"../../theme.plm\"
//
// It declares no name palette.plm declares, so nothing in the shell changes
// meaning when a scene opts in; a rewritten import re-themes a running scene.

library Skin strict {

    // colors.background, the QS fallback #ff000000 (opaque part): no wallpaper was sampled.
    let skin.coal = #000000

    // colors.surfaceVariant, the QS fallback #242A35: no wallpaper was sampled.
    let skin.surface = #242A35

    // colors.text.primary, the QS fallback #CBD6E5: no wallpaper was sampled.
    let skin.ink = #CBD6E5

    // colors.text.secondary (Settings/colors.jsonc) in the dark theme, its own dark tone
    // in the light one — not a mix of the two sampled tones.
    let skin.ink.dim = #AEB9C8

    // colors.accent.primary, the QS fallback #006FCC: no wallpaper was sampled.
    let skin.accent = #006FCC
    // Theme.accentHover: towardsWhite(accentPrimary, 0.2).
    let skin.accent.hover = mix(skin.accent, #ffffff, 20%)
    // Theme.accentDarkStrong: towardsBlack(accentPrimary, 0.8).
    let skin.accent.deep = mix(skin.accent, skin.coal, 80%)
    // colors.onAccent, unchanged.
    let skin.on.accent = #ffffff

    // Is the theme light? True when this palette is the light one — the wallpaper is
    // light on its mean WCAG luminance (the same 0.5 the reference uses), or
    // --mode/~/.config/pleamar/theme.mode forced it. A scene reads it to pick the part
    // of a design that only one theme has, never to patch the ink: the ink is here.
    let skin.light = false
}
";
        assert_eq!(fallback_theme().render("2026-11-02T21:27:41Z"), expected);
    }
}
