//! Regenerate `hosts/trantor/unbound-hosts.nix` from its sources.
//!
//! Merges the hand-curated local entries (`hosts/trantor/unbound-local.txt`,
//! `host A|AAAA value`) with the upstream malware-hosts snapshot
//! (`files/sources/malw-hosts.txt`, raw hosts format), dropping every name the
//! allow-list keeps resolving (`files/sources/malw-hosts-allow.txt`).
//!
//!     gen-unbound-hosts [REPO_ROOT]     (default: git rev-parse --show-toplevel)
//!
//! Port of `packages/local-bin/scripts/gen-unbound-hosts`.

use std::path::{Path, PathBuf};
use std::process::Command;

const HEADER: &str = "\
# Generated by `gen-unbound-hosts` — do not edit by hand.
# Sources: hosts/trantor/unbound-local.txt (local entries) +
#          files/sources/malw-hosts.txt (upstream snapshot),
#          minus the names in files/sources/malw-hosts-allow.txt.
# Regenerate with: just unbound-hosts
[
";

/// `host A|AAAA value` → `host. TYPE value`.
fn parse_local(line: &str) -> Option<String> {
    let parts: Vec<&str> = line.split_whitespace().collect();
    if parts.len() == 3 && (parts[1] == "A" || parts[1] == "AAAA") {
        return Some(format!("{}. {} {}", parts[0], parts[1], parts[2]));
    }
    None
}

/// Raw hosts line `ip host [host…]` → one unbound `local-data` per host.
fn parse_upstream(line: &str) -> Vec<String> {
    let parts: Vec<&str> = line.split_whitespace().collect();
    if parts.len() < 2 || parts[0].starts_with('#') {
        return Vec::new();
    }
    let ip = parts[0];
    let kind = if ip.contains(':') { "AAAA" } else { "A" };
    parts[1..]
        .iter()
        .map(|host| format!("{host}. {kind} {ip}"))
        .collect()
}

fn repo_root(argument: Option<&str>) -> Result<PathBuf, String> {
    if let Some(path) = argument {
        return std::fs::canonicalize(path).map_err(|exc| format!("{path}: {exc}"));
    }
    let output = Command::new("git")
        .args(["rev-parse", "--show-toplevel"])
        .output()
        .map_err(|exc| format!("cannot run git: {exc}"))?;
    if !output.status.success() {
        return Err("git rev-parse --show-toplevel failed".to_string());
    }
    let text = String::from_utf8_lossy(&output.stdout).trim().to_string();
    std::fs::canonicalize(&text).map_err(|exc| format!("{text}: {exc}"))
}

/// The rendered file plus the number of entries it holds.
pub fn render(root: &Path) -> Result<(String, usize), String> {
    let read = |relative: &str| -> Result<String, String> {
        std::fs::read_to_string(root.join(relative)).map_err(|exc| format!("{relative}: {exc}"))
    };

    let mut local: Vec<String> = Vec::new();
    for line in read("hosts/trantor/unbound-local.txt")?.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(entry) = parse_local(line) {
            local.push(entry);
        }
    }

    let allowed: Vec<String> = read("files/sources/malw-hosts-allow.txt")?
        .lines()
        .filter(|line| !line.trim().is_empty() && !line.trim().starts_with('#'))
        .map(|line| line.split_whitespace().next().unwrap_or("").to_string())
        .collect();

    let mut upstream: Vec<String> = Vec::new();
    for line in read("files/sources/malw-hosts.txt")?.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        for entry in parse_upstream(line) {
            let name = entry.split_whitespace().next().unwrap_or("");
            let name = name.strip_suffix('.').unwrap_or(name);
            if !allowed.iter().any(|allowed| allowed == name) && !upstream.contains(&entry) {
                upstream.push(entry);
            }
        }
    }
    upstream.sort();

    let mut entries = local;
    entries.extend(upstream);
    let body: Vec<String> = entries
        .iter()
        .map(|entry| format!("  \"{entry}\""))
        .collect();
    let rendered = format!("{HEADER}{}\n]\n", body.join("\n"));
    Ok((rendered, entries.len()))
}

fn main() -> std::process::ExitCode {
    let argument = std::env::args().nth(1);
    let root = match repo_root(argument.as_deref()) {
        Ok(root) => root,
        Err(exc) => {
            eprintln!("gen-unbound-hosts: {exc}");
            return std::process::ExitCode::from(1);
        }
    };
    let (rendered, count) = match render(&root) {
        Ok(result) => result,
        Err(exc) => {
            eprintln!("gen-unbound-hosts: {exc}");
            return std::process::ExitCode::from(1);
        }
    };
    let out_path = root.join("hosts/trantor/unbound-hosts.nix");
    if let Err(exc) = std::fs::write(&out_path, rendered) {
        eprintln!(
            "gen-unbound-hosts: cannot write {}: {exc}",
            out_path.display()
        );
        return std::process::ExitCode::from(1);
    }
    println!(
        "gen-unbound-hosts: wrote {} ({count} entries)",
        out_path.display()
    );
    std::process::ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_entries_need_the_type_column() {
        assert_eq!(
            parse_local("nas A 192.168.0.5"),
            Some("nas. A 192.168.0.5".to_string())
        );
        assert_eq!(
            parse_local("nas AAAA fd00::5"),
            Some("nas. AAAA fd00::5".to_string())
        );
        assert_eq!(parse_local("nas CNAME 192.168.0.5"), None);
        assert_eq!(parse_local("nas A"), None);
    }

    #[test]
    fn upstream_lines_expand_per_host() {
        assert_eq!(
            parse_upstream("0.0.0.0 ads.example tracker.example"),
            vec![
                "ads.example. A 0.0.0.0".to_string(),
                "tracker.example. A 0.0.0.0".to_string()
            ]
        );
        assert_eq!(
            parse_upstream("::1 v6.example"),
            vec!["v6.example. AAAA ::1".to_string()]
        );
        assert!(parse_upstream("# comment").is_empty());
        assert!(parse_upstream("0.0.0.0").is_empty());
    }

    #[test]
    fn rendering_merges_local_first_then_sorted_upstream() {
        let dir = std::env::temp_dir().join(format!("gen-unbound-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("hosts/trantor")).unwrap();
        std::fs::create_dir_all(dir.join("files/sources")).unwrap();
        std::fs::write(
            dir.join("hosts/trantor/unbound-local.txt"),
            "# comment\nnas A 192.168.0.5\nrouter AAAA fd00::1\nbad line here\n",
        )
        .unwrap();
        std::fs::write(
            dir.join("files/sources/malw-hosts-allow.txt"),
            "# keep these\nkeep.example\n",
        )
        .unwrap();
        std::fs::write(
            dir.join("files/sources/malw-hosts.txt"),
            "0.0.0.0 zebra.example keep.example\n0.0.0.0 alpha.example\n",
        )
        .unwrap();
        let (rendered, count) = render(&dir).expect("render");
        assert_eq!(count, 4);
        assert!(
            rendered.starts_with("# Generated by `gen-unbound-hosts`"),
            "{rendered}"
        );
        assert!(rendered.contains("  \"nas. A 192.168.0.5\""), "{rendered}");
        assert!(
            rendered.contains("  \"router. AAAA fd00::1\""),
            "{rendered}"
        );
        // Upstream is sorted and the allow-listed name is gone.
        assert!(!rendered.contains("keep.example"), "{rendered}");
        let alpha = rendered.find("alpha.example").expect("alpha");
        let zebra = rendered.find("zebra.example").expect("zebra");
        assert!(alpha < zebra, "{rendered}");
        assert!(rendered.ends_with("]\n"), "{rendered}");
        std::fs::remove_dir_all(&dir).ok();
    }
}
