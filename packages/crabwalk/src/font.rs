fn table() -> &'static HashMap<char, [u8; GLYPH_H as usize]> {
    static TABLE: OnceLock<HashMap<char, [u8; GLYPH_H as usize]>> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut map = HashMap::new();
        for (ch, rows) in GLYPHS {
            let mut glyph = [0u8; GLYPH_H as usize];
            for (i, row) in rows.split('/').enumerate() {
                let mut bits = 0u8;
                for (j, c) in row.chars().enumerate() {
                    if c == '1' {
                        bits |= 1 << (GLYPH_W as usize - 1 - j);
                    }
                }
                glyph[i] = bits;
            }
            map.insert(*ch, glyph);
        }
        map
    })
}

pub fn glyph(c: char) -> Option<[u8; GLYPH_H as usize]> {
    let upper = c.to_uppercase().next().unwrap_or(c);
    table().get(&upper).copied()
}

/// Width of a string in glyph pixels at scale 1 with the given letter scale.
pub fn text_width(text: &str, scale: i32) -> i32 {
    let chars = text.chars().count() as i32;
    if chars == 0 {
        0
    } else {
        chars * (GLYPH_W + SPACING) * scale - SPACING * scale
    }
}
