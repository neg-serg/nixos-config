//! Shell integration: the wrappers that put a colouriser in front of the tools
//! that print plain text.
//!
//! The generated code is deliberately boring: a guarded function per command
//! that calls `tint` with an explicit ruleset. Two properties matter.
//!
//! - Nothing is wrapped that is not installed, so the same output can be used
//!   on every host.
//! - Pipes stay untouched. `tint` itself notices when its stdout is not a
//!   terminal and `exec`s the command, so `df | grep x` keeps its exit code and
//!   costs one `exec` instead of a copy through the colouriser.

use crate::config::Config;
use crate::ruleset;

/// Merge the built-in command map with the user's `wrap =`/`skip =` lists.
///
/// Returns `(ruleset, commands)` pairs, sorted by ruleset name, de-duplicated
/// and with skipped commands removed.
pub fn wrappers(config: &Config) -> Vec<(String, Vec<String>)> {
    let mut map: Vec<(String, Vec<String>)> = ruleset::WRAPPERS
        .iter()
        .map(|(ruleset, commands)| {
            (
                (*ruleset).to_string(),
                commands.iter().map(|c| (*c).to_string()).collect(),
            )
        })
        .collect();
    for command in &config.extra_wrappers {
        let ruleset = ruleset::for_command(command).to_string();
        match map.iter_mut().find(|(name, _)| *name == ruleset) {
            Some((_, commands)) => commands.push(command.clone()),
            None => map.push((ruleset, vec![command.clone()])),
        }
    }
    for (ruleset_name, commands) in map.iter_mut() {
        commands.retain(|command| !config.skip_wrappers.contains(command));
        // A ruleset that owns a pager, an editor or an interactive prompt stays
        // out of the shell integration unless the config asked for its commands
        // (`wrap`/`pty`/`pager`).
        if ruleset::EXPLICIT_ONLY.contains(&ruleset_name.as_str()) {
            commands.retain(|command| config.extra_wrappers.contains(command));
        }
        commands.sort();
        commands.dedup();
    }
    map.retain(|(_, commands)| !commands.is_empty());
    map.sort_by(|a, b| a.0.cmp(&b.0));
    map
}

/// Render the integration script for one shell.
pub fn emit(shell: &str, config: &Config) -> Result<String, String> {
    let wrappers = wrappers(config);
    match shell {
        "zsh" => Ok(emit_sh_like(&wrappers, ShellKind::Zsh, config)),
        "bash" => Ok(emit_sh_like(&wrappers, ShellKind::Bash, config)),
        "fish" => Ok(emit_fish(&wrappers, config)),
        "list" => Ok(wrappers
            .iter()
            .flat_map(|(ruleset, commands)| {
                commands
                    .iter()
                    .map(move |command| format!("{command} {ruleset}\n"))
            })
            .collect()),
        other => Err(format!(
            "unknown shell `{other}`; expected zsh, bash, fish or list"
        )),
    }
}

/// `--pty` or `--pager` for the commands that need one, empty otherwise.
///
/// The built-in sets stay conservative: `--pty` is never on by default, because
/// a relay bug in a build command is worse than no colour, and `--pager` only
/// covers `systemctl` (one screen, `less` quits after printing it). Everything
/// else is one config line away — `pty = "cargo rustc"`, `pager = "journalctl"`.
fn wrapper_mode(command: &str, config: &Config) -> &'static str {
    if config.pty_wrapped.iter().any(|c| c == command) || ruleset::PTY_WRAPPED.contains(&command) {
        " --pty"
    } else if config.pager_wrapped.iter().any(|c| c == command)
        || ruleset::PAGER_WRAPPED.contains(&command)
    {
        " --pager"
    } else {
        ""
    }
}

#[derive(Clone, Copy)]
enum ShellKind {
    Zsh,
    Bash,
}

fn emit_sh_like(wrappers: &[(String, Vec<String>)], kind: ShellKind, config: &Config) -> String {
    let mut out = String::new();
    out.push_str("# tint shell integration: colourise the programs that print plain text.\n");
    out.push_str("# Generated by `tint --shell zsh|bash`; edit the config, not this output.\n");
    out.push_str("# Pipes are untouched: tint execs the command when stdout is not a tty.\n");
    out.push_str(&format!(
        "# Not wrapped on purpose (pager/progress/tty): {}\n",
        ruleset::EXPLICIT_ONLY.join(", ")
    ));
    for (ruleset, commands) in wrappers {
        for command in commands {
            let guard = match kind {
                ShellKind::Zsh => format!("if (( $+commands[{command}] )); then"),
                ShellKind::Bash => format!("if command -v {command} >/dev/null 2>&1; then"),
            };
            out.push_str(&guard);
            out.push('\n');
            out.push_str(&format!(
                "  {command}() {{ command tint -r {ruleset}{} -- {command} \"$@\"; }}\n",
                wrapper_mode(command, config)
            ));
            out.push_str("fi\n");
        }
    }
    out
}

fn emit_fish(wrappers: &[(String, Vec<String>)], config: &Config) -> String {
    let mut out = String::new();
    out.push_str("# tint shell integration: generated by `tint --shell fish`.\n");
    for (ruleset, commands) in wrappers {
        for command in commands {
            out.push_str(&format!("if command -q {command}\n"));
            out.push_str(&format!(
                "    function {command} --wraps {command} --description 'tint: {ruleset}'\n"
            ));
            out.push_str(&format!(
                "        command tint -r {ruleset}{} -- {command} $argv\n",
                wrapper_mode(command, config)
            ));
            out.push_str("    end\n");
            out.push_str("end\n");
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_wrappers_include_the_obvious_tools() {
        let map = wrappers(&Config::default());
        let flat: Vec<&str> = map
            .iter()
            .flat_map(|(_, commands)| commands.iter().map(|c| c.as_str()))
            .collect();
        for expected in ["df", "lsblk", "ip", "ss", "dmesg", "free", "sensors"] {
            assert!(flat.contains(&expected), "{expected} missing from wrappers");
        }
        // Anything pager-, progress- or tty-driven must stay out: the child
        // would see a pipe instead of a terminal.
        for excluded in [
            "git",
            "man",
            "less",
            "docker",
            "kubectl",
            "python",
            "python3",
            "curl",
            "make",
            "cargo",
            "nix",
            "nh",
            "journalctl",
            "rsync",
        ] {
            assert!(!flat.contains(&excluded), "{excluded} must not be wrapped");
        }
    }

    #[test]
    fn skip_and_wrap_are_honoured() {
        let mut config = Config::default();
        config.skip_wrappers.push("find".to_string());
        config.extra_wrappers.push("go".to_string());
        let map = wrappers(&config);
        let flat: Vec<String> = map
            .iter()
            .flat_map(|(_, commands)| commands.clone())
            .collect();
        assert!(!flat.contains(&"find".to_string()));
        assert!(flat.contains(&"go".to_string()));
    }

    #[test]
    fn wrappers_carry_the_mode_they_need() {
        let script = emit("zsh", &Config::default()).unwrap();
        // Conservative defaults: `--pty` only by config, `--pager` for systemctl.
        assert!(script.contains("dmesg() { command tint -r dmesg -- dmesg \"$@\"; }"));
        assert!(script
            .contains("systemctl() { command tint -r systemctl --pager -- systemctl \"$@\"; }"));
        assert!(!script.contains("cargo()"), "cargo is opt-in");

        // Opting in through the config adds both the wrapper and its mode.
        let mut config = Config::default();
        config.extra_wrappers.push("cargo".to_string());
        config.pty_wrapped.push("cargo".to_string());
        config.extra_wrappers.push("journalctl".to_string());
        config.pager_wrapped.push("journalctl".to_string());
        let opted_in = emit("zsh", &config).unwrap();
        assert!(opted_in.contains("cargo() { command tint -r cargo --pty -- cargo \"$@\"; }"));
        assert!(opted_in
            .contains("journalctl() { command tint -r journalctl --pager -- journalctl \"$@\"; }"));
    }

    #[test]
    fn zsh_output_is_guarded_and_quoted() {
        let script = emit("zsh", &Config::default()).unwrap();
        assert!(script.contains("if (( $+commands[df] )); then"));
        assert!(script.contains("df() { command tint -r df -- df \"$@\"; }"));
        assert!(script.contains("fi"));
    }

    #[test]
    fn bash_output_uses_command_v() {
        let script = emit("bash", &Config::default()).unwrap();
        assert!(script.contains("if command -v df >/dev/null 2>&1; then"));
    }

    #[test]
    fn fish_output_uses_functions() {
        let script = emit("fish", &Config::default()).unwrap();
        assert!(script.contains("function df --wraps df"));
        assert!(script.contains("command tint -r df -- df $argv"));
    }

    #[test]
    fn unknown_shell_is_an_error() {
        assert!(emit("tcsh", &Config::default()).is_err());
    }
}
