#!/usr/bin/env bash
# Regenerate THEME-AUDIT.md from the Rust theme.
#
# The palette has exactly one source of truth — `src/theme.rs` — so this script dumps each
# variant with `theme-dump`, runs the Python auditor over the dump, and concatenates the
# reports into one document. Nothing in the audit is hand-written: re-running it is the only
# way the numbers in the markdown can drift from the colours the app paints.
#
#   ./tools/theme-audit/audit.sh          # rewrite THEME-AUDIT.md
#   ./tools/theme-audit/audit.sh --check  # fail if the file is stale (for CI)
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
report="$root/THEME-AUDIT.md"
pairs="$here/neg-pairs.json"
hues="text,text_dim,text_faint,accent,accent2,warn,danger,success"

# cargo is a rustup shim and dies on the session's LD_LIBRARY_PATH (glibc private symbols),
# which is the same trap the prototype's README documents for any Rust build on this host.
cargo_run() { env -u LD_LIBRARY_PATH /run/current-system/sw/bin/cargo "$@"; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

fail=0
{
  cat <<'HEADER'
# Theme audit

Generated by `tools/theme-audit/audit.sh` — do not edit by hand. The palette is read out of
`src/theme.rs` with `theme-dump`, so every number below describes the colours the app actually
paints.

## What is measured, and why these three measures

A palette can fail a reader in three independent ways, so all three are reported for every
pair:

1. **WCAG 2.1 contrast** — the ratio of relative luminances, the only measure that has a
   normative threshold. 4.5:1 is AA for normal text, 3.0:1 is AA for large text and for
   non-text UI (WCAG 1.4.11).
2. **Euclidean distance in OKLab** (`dOK`) — a perceptually uniform space, so the distance is
   proportional to what the eye notices. 0.02 is a just-noticeable difference on a large patch,
   0.05 is clear. This is the measure that catches "two greys that look identical but measure
   different".
3. **CIEDE2000** — the CIE's own colour-difference formula, reported for continuity with the
   colour literature (its JND is ~2.3).

On top of that the same two measures are recomputed after simulating **protanopia,
deuteranopia and tritanopia** (Machado, Oliveira & Fernandes 2009, severity 1.0, applied in
linear light). A pair that is separated only by hue collapses under those; a pair separated by
lightness survives. That is the reason the app's row states are checked by lightness first.

## How the palette relates to neg.nvim

`neg.nvim` is a "pure dark" terminal theme: pure black ground, one blue-grey ink family, and
hues reserved for meaning. Its chrome tones are deliberately sub-AA (comment 1.97:1, LineNr
1.71:1) because a terminal glyph is 12 px of solid ink. A GPU UI paints 11-13 px captions and
2 px rules, so the app keeps neg's hue and chroma but re-derives lightness wherever the theme's
own value would fall under 4.5:1 — that is the `derived(...)` marker next to such a token in
`src/theme.rs`, and the audit below is what proves the result.

HEADER

  for variant in neg neg-soft neg-hc; do
    cargo_run run --release --quiet --manifest-path "$root/Cargo.toml" --bin theme-dump -- "$variant" \
      > "$tmp/$variant.json"
    if ! python3 "$here/theme_audit.py" "$tmp/$variant.json" --pairs "$pairs" --hues "$hues" \
      --md "$tmp/$variant.md" > "$tmp/$variant.log" 2>&1; then
      fail=1
    fi
    echo "---"
    echo
    sed -n '2,$p' "$tmp/$variant.md" | sed "1i ## Variant \`$variant\`"
    echo
    echo '### Constraint check'
    echo
    grep -E '^(VIOLATION|selftest)' "$tmp/$variant.log" | sed 's/^/    /' || true
    if grep -q '^VIOLATION' "$tmp/$variant.log"; then
      echo
      echo '**A required pair is below its floor — see the lines above.**'
    else
      echo
      echo 'Every pair marked `min` in `neg-pairs.json` holds.'
    fi
    echo
  done
} > "$tmp/THEME-AUDIT.md.new"

if [ "${1:-}" = "--check" ]; then
  if ! diff -q "$report" "$tmp/THEME-AUDIT.md.new" > /dev/null 2>&1; then
    echo "THEME-AUDIT.md is stale; run tools/theme-audit/audit.sh" >&2
    exit 1
  fi
  echo "THEME-AUDIT.md is up to date"
  exit $fail
fi

mv "$tmp/THEME-AUDIT.md.new" "$report"
echo "wrote $report"
exit $fail
