// --- 2b. literals the extraction regex cannot see --------------------------
// Nested template literals inside `${}` (the outer match swallows the inner
// opening backtick, so the inner literal never appears in `literals` above).
// Keyed by exact raw text (including quotes) -> full replacement text.
// prettier-ignore
const EXTRAS = [
  ["`，会话截断到 seq ${r.truncatedTo}`", "`, сессия усечена до seq ${r.truncatedTo}`"],
];

// --- 3. build map ---------------------------------------------------------
const entries = [];
for (let i = 0; i < literals.length; i++) {
  const src = literals[i];
  const ru = T.get(i);
  if (ru === undefined) continue; // left untranslated (comment fragment)
  const quote = src[0];
  const value = quote + ru + quote;
  if (src.length === value.length && src === value) {
    console.error(`gen: translation ${i} identical to source — refusing: ${JSON.stringify(src)}`);
    process.exit(1);
  }
  entries.push([src, value]);
}
for (const [src, value] of EXTRAS) {
  if (!raw.includes(src)) {
    console.error(`gen: extra key not found in bundle: ${JSON.stringify(src)}`);
    process.exit(1);
  }
  entries.push([src, value]);
}

// sort longest-first so overlapping literals replace correctly
entries.sort((a, b) => b[0].length - a[0].length);

// --- 4. verify every key occurs ------------------------------------------
const missing = entries.filter(([k]) => !raw.includes(k));
if (missing.length) {
  console.error(`gen: ${missing.length} keys not found in bundle:`);
  for (const [k] of missing) console.error("  " + JSON.stringify(k));
  process.exit(1);
}

// --- 5. apply in memory + syntax check ------------------------------------
let patched = raw;
for (const [k, v] of entries) patched = patched.split(k).join(v);
const leftovers = entries.filter(([k]) => patched.includes(k));
if (leftovers.length) {
  console.error(`gen: ${leftovers.length} keys still present after patch:`);
  for (const [k] of leftovers) console.error("  " + JSON.stringify(k));
  process.exit(1);
}
const checkFile = "/tmp/dsh-tui-check.mjs";
fs.writeFileSync(checkFile, patched);
try {
  execFileSync(process.execPath, ["--check", checkFile], { stdio: "pipe" });
} catch (e) {
  console.error("gen: syntax check failed on patched bundle:");
  console.error(String(e.stderr ?? e));
  process.exit(1);
}

// --- 6. write i18n.json ----------------------------------------------------
const map = Object.fromEntries(entries);
fs.writeFileSync(outPath, JSON.stringify(map, null, 2) + "\n");
console.log(
  `gen: wrote ${outPath} — ${entries.length} translations (${literals.length - entries.length} literals left as-is)`
);
