-- =====================================================================
-- Autostart (autostart.conf / env.conf) -- NixOS-appropriate
-- =====================================================================
-- The login layer is a session-lock surface inside this compositor
-- (files/pleamar/shells/lock/lock.plm), so the login screen is painted by the
-- same compositor that will run the session: no greeter process exits, no second
-- Hyprland, no DRM mode re-set on login. The layer process itself is
-- `pleamar-login-layer` (modules/user/session/greetd/login-layer.sh).
--
-- Phase detection reads the marker the session wrapper maintains and exports:
--   $PLEAMAR_LOGIN_STATE_DIR/state   "login" | "session"   (see greetd/session-wrapper.sh)
-- The directory sits in XDG_RUNTIME_DIR, which logind wipes when the session
-- ends — a logout therefore always comes back to the login screen, with nobody
-- having to reset the marker. No PLEAMAR_LOGIN_STATE_DIR (a compositor started by
-- hand, outside greetd) means session phase.
local loginStateDir = os.getenv("PLEAMAR_LOGIN_STATE_DIR")
local loginPhase = (function()
  if not loginStateDir then return false end
  local f = io.open(loginStateDir .. "/state", "r")
  if not f then return false end
  local v = f:read("*l") or ""
  f:close()
  return v:match("^%s*login%s*$") ~= nil
end)()

-- Everything that starts once the compositor is up and the login layer (if any)
-- has released the screen: the desktop apps and the long-running helpers that
-- have no systemd unit of their own. Called by the login handover below through
-- `hyprctl eval "hl.session_start()"` and by the fresh-start branch; keep it
-- idempotent, the rescue bind can call it a second time.
hl.session_start = function()
  hl.exec_cmd("systemctl --user start wl-daemon.service")
  hl.exec_cmd("wl-restore")
  hl.exec_cmd("kitty --single-instance --class term")
  -- Only the on-demand launcher is on PATH (modules/user/session/chat.nix): the
  -- package's own executable is `Telegram` and the launcher builds it on first
  -- run, so a bare `Telegram` here was a dead exec after Telegram left the
  -- system closure (2026-11-03).
  hl.exec_cmd("telegram-desktop")
  -- wl-clip-persist is a single daemon: a rescue/fresh restart must not stack
  -- a second copy, and the cliphist watcher is replaced the same way.
  hl.exec_cmd("sh -c 'pkill -x wl-clip-persist 2>/dev/null; wl-clip-persist --clipboard regular'")
  hl.exec_cmd("zsh -c 'pkill \"wl-paste --watch cliphist store\"; wl-paste --watch cliphist store'")
  hl.exec_cmd("nicotine -s") -- start hidden (Soulseek client); summon via special-submap d
  hl.exec_cmd("wayscriber --daemon") -- keep the annotation overlay resident; M4+SHIFT+Z toggles it
  hl.exec_cmd("systemctl --user start --no-block vicinae.service")
  -- Warm the menu-search entry cache once the tray apps have registered their
  -- StatusNotifierItems: the window is fed from that cache, so Super+Shift+M
  -- opens without walking the bus for every menu (menu-search --refresh; it also
  -- refreshes in the background on every use).
  hl.exec_cmd("zsh -c 'sleep 8; menu-search --refresh'")
  hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP HYPRLAND_INSTANCE_SIGNATURE QT_XDG_DESKTOP_PORTAL QT_QPA_PLATFORMTHEME")
  hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP HYPRLAND_INSTANCE_SIGNATURE QT_XDG_DESKTOP_PORTAL QT_QPA_PLATFORMTHEME")
end

-- Rescue bind: top-level so a config reload keeps it. While a session lock is
-- up the lock surface owns the input, so it is usable only when no lock is up —
-- after a failed login layer, or in a hand-started compositor. It writes
-- "session", starts the target and runs the apps/helpers.
hl.bind(M4 .. "+" .. SH .. "+F12", hl.dsp.exec_cmd(
  "sh -c 'printf \"session\\n\" > \"${PLEAMAR_LOGIN_STATE_DIR:-/tmp}/state\"; hypr-start && hyprctl eval \"hl.session_start()\"'"
))

hl.on("hyprland.start", function()
  -- Plugin loads come first, *before* the phase split below: the compositor parses
  -- this file once, and the login branch returns before reaching anything that sits
  -- in the session branch — a greetd login (the way this box normally starts) then
  -- left hyprexpo unloaded for the whole session, because nothing re-parses the
  -- config after the password (hypr-start restarts units, it does not reload).
  -- The workspace capsule click then evaluated hl.plugin.hyprexpo.* on a nil
  -- namespace: hyprctl answers "ok" and no overview ever appears. These plugins
  -- are passive (nothing is painted until they are asked to), so loading them
  -- while the login layer is up is harmless. hy3 comes up here too: loading it
  -- pre-login is what makes it the layout for the whole session (nothing
  -- re-parses the config after the password), and it has nothing to paint before
  -- windows exist. The glass plugin deliberately stays out of this hook: its
  -- own unit loads and configures it after the login layer is gone, and the login
  -- screen must not be glazed. Re-runnable in a live session:
  -- `hy3-setup` / `hyprexpo-setup` /
  -- `hyprwindowshade-setup` / `hyprwinwrap-setup` / `gloview-setup` /
  -- `hymission-setup` (also in PATH).
  hl.exec_cmd("@hy3_setup@")
  hl.exec_cmd("@hyprexpo_setup@")
  hl.exec_cmd("@hyprwindowshade_setup@")
  hl.exec_cmd("@hyprwinwrap_setup@")
  hl.exec_cmd("@gloview_setup@")
  hl.exec_cmd("@hymission_setup@")

  -- 0.57 port status: only hy3 is built (overlay.nix `ported`). The other
  -- setup helpers above are stubs, so the hyprexpo/hymission/... binds are
  -- no-ops until those plugins are ported.

  -- The layout the shell's scenes start with, remembered for the reload handler
  -- below: pleamar reads `screen.width` once per scene, so a scale change applied
  -- later by `hyprctl reload` leaves every right-anchored row behind the surface
  -- until the scene set is restarted.
  hl.exec_cmd("pleamar-scale-guard --record")

  if loginPhase then
    -- Login phase: start the login layer instead of the desktop. Nothing of the
    -- session (target, shell, autostart apps) is started yet; the layer writes
    -- "session" into the marker and releases the lock scene, then the login
    -- shell starts the session target and runs hl.session_start().
    --
    -- The wallpaper behind the login screen is started by the layer itself
    -- (pleamar-login-layer, its "wallpaper behind the login screen" block), not
    -- from here. An exec dispatched while this file is parsed reaches the user
    -- manager before WAYLAND_DISPLAY can be imported into it, so a wl-daemon
    -- started from this branch dies with "Could not find wayland compositor" and
    -- stays down until the session target comes up after the password — the
    -- desktop then appeared on the bare compositor background (2026-11-04
    -- 00:38:11-21). The layer runs with the compositor's environment and
    -- publishes the same file into the lock scene's data folder, so the login
    -- draws the picture the desktop behind it is painted with.

    -- hyprctl dispatch exec returns immediately (the command is backgrounded),
    -- so this never blocks the config load.
    --
    -- The three attempts cover a layer that crashed before the password was
    -- entered: without them the compositor would sit on a black screen with
    -- nothing able to reach it. They are not a lockout risk either — if the
    -- layer did come up, the session lock owns the input and the attempts never
    -- run again. If all three fail there is no lock in place, so the rescue
    -- bind (registered above) still gets the desktop started.
    hl.exec_cmd([[
      sh -c '
        for _ in 1 2 3; do
          pleamar-login-layer
          if grep -qx session "${PLEAMAR_LOGIN_STATE_DIR:-/tmp}/state" 2>/dev/null; then
            hypr-start --login && hyprctl eval "hl.session_start()"
            exit 0
          fi
          sleep 1
        done
        printf "login layer exited without a login, three times, at %s\n" "$(date)" >> /tmp/pleamar-login-layer.log
      '
    ]])
    return
  end

  -- Fresh-compositor phase (after a crash, by hand, or the rescue bind): restart
  -- the session target chain: import env, clean stale portals and stop/start
  -- hyprland-session.target so the pleamar scenes (bar,
  -- launcher, panels, notifications, toast), hypridle, hyprscratch and ru-layout
  -- come back after a Hyprland (re)start. Every pleamar unit is `PartOf=` +
  -- `WantedBy=hyprland-session.target` (modules/user/nix-maid/gui/pleamar.nix),
  -- so restarting the target restarts them and nothing else has to say so.
  hl.exec_cmd("hypr-start")


  -- Dynamic cursors (stretch): this exec only covers a hand-started compositor
  -- (no login phase) — after a greetd login nothing re-parses the config, so
  -- the `hyprdynamiccursors` user unit loads the plugin with
  -- hyprland-session.target instead (see main.nix). The login screen keeps the
  -- stock cursor either way. Re-runnable: `hyprdynamiccursors-setup`.
  hl.exec_cmd("@hyprdynamiccursors_setup@")

  -- HyprExpo and HyprWindowShade are loaded above, before the login branch — they
  -- must come up in the login phase too (see the comment at the top of this handler).

  hl.exec_cmd("systemctl --user restart hyprscratch.service")
  hl.session_start()
end)

-- Ensure the shell's bar is running after every config reload
-- (systemctl start is a no-op when the service is already active,
-- so this never spawns more than one instance); pleamar-health.timer is the
-- watchdog that brings back a scene which stopped answering on its own.
--
-- A reload is also where the monitor scale can change under the shell, and a
-- scene reads `screen.width` exactly once. `pleamar-scale-guard --check`
-- compares the live layout with the one `hyprland.start` recorded and, when it
-- changed, hard-restarts the whole scene set (SIGKILL of each unit's cgroup, so
-- the stale geometry cannot survive a polite stop). Measured 2026-11-05: a
-- 1x -> 2x reload moved the bar's media capsule, gear and Genelec past its
-- 1920 px surface, and the bar kept answering — a plain `start` cannot see
-- that. The guard runs behind the login screen too, where it only records:
-- the login layer owns the screen and no scene is up to restart.
hl.on("config.reloaded", function()
  hl.exec_cmd("pleamar-scale-guard --check")
  -- Not during the login phase: the marker still says "login", the login layer
  -- owns the screen, and a reload (or the desktop shell starting behind the
  -- login screen) would put the panel on top of it.
  if loginPhase then return end
  hl.exec_cmd("systemctl --user start pleamar-bar.service")
end)

-- Keep the primary monitor as the home for all workspaces
hl.on("monitor.added", function(monitor)
  -- A new monitor changes the layout the scenes laid themselves out against;
  -- the guard restarts the set only when the logical layout really changed.
  hl.exec_cmd("pleamar-scale-guard --check")
  if not monitor or monitor.name ~= "DP-2" then return end
  hl.exec_cmd("systemctl --user restart hyprscratch.service")
  for _, ws in ipairs(hl.get_workspaces()) do
    -- Special workspaces have no numbered id; leave them alone.
    if ws.id ~= nil and ws.monitor and ws.monitor.name ~= "DP-2" then
      hl.dispatch(hl.dsp.workspace.move({ workspace = ws.id, monitor = "DP-2" }))
    end
  end
end)

hl.on("monitor.removed", function(monitor)
  if monitor and monitor.name == "DP-2" then
    hl.exec_cmd("notify-send -u low 'Monitor DP-2 disconnected'")
  end
end)
