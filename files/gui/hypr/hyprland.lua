-- stock cursor) and true on reloads. Keep the values in sync with
-- files/gui/hypr/hyprdynamiccursors.lua — `enabled = false` there too: the
-- stretch effect is off by default because it distorts the pointer in games;
-- the `cursor-stretch` helper is the runtime opt-in for one session and has no
