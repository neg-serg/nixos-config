-- ---------------------------------------------------------------------
-- Layout-agnostic binds
-- ---------------------------------------------------------------------
-- One key = one intent; the layoutmsg is picked from the ACTIVE workspace algorithm:
-- hl.get_active_workspace().tiled_layout is "hy3" for a hy3 workspace and
-- "scrolling"/"master" (verified on 0.56.2) for the core fallbacks. One keymap
-- therefore works wherever the tape/master fallback is in use instead of going
-- silent, and on hy3 the tape keys are a no-op (no "other" argument below).
local function layoutAlgo()
  local ws = hl.get_active_workspace()
  return ws and ws.tiled_layout or ""
end

-- L(tape, master, other) takes layoutmsg strings; the dispatcher is built at press
-- time (like the hyprexpo bind) so no dispatcher objects outlive a reload.
local function L(scrolling, master, other)
  return function()
    local algo = layoutAlgo()
    local cmd  = algo == "scrolling" and scrolling or (algo == "master" and master or other)
    if cmd then return hl.dispatch(hl.dsp.layout(cmd)) end
  end
end

-- hy3 dispatchers from Lua. hy3 is loaded *after* this file is parsed, so
-- hl.plugin.hy3 is nil while the binds below are declared: resolve the namespace
-- at press time and skip silently when the plugin is not there. The factories
-- return dispatcher objects, and those are run with hl.dispatch — a dispatcher
-- object cannot be called directly (Hyprland: "use hl.dispatch(dispatcher)").
local function hy3(factory)
  return function()
    local plugin = hl.plugin and hl.plugin.hy3
    if plugin then return hl.dispatch(factory(plugin)) end
  end
end

-- Detach, then shrink the floating node to DETACH_SCALE of the box it had in the
-- layout. The local detach/float patch adds hy3.detach, so a stock hy3 (or a
-- session where the patched .so failed to load) makes the bind a silent no-op
-- rather than a Lua error on every press. The patch keeps that box on purpose (neighbours must not reflow), so on
-- a one-window workspace the float would cover exactly the screen and the press
-- would look like a no-op; ion3's detach is visibly smaller for the same reason.
-- Hyprland's relative resize grows and shrinks around the window's centre, so no
-- extra move is needed, and reattaching restores the tiled box on its own.
local DETACH_SCALE = 0.7
local function hy3detach()
  local plugin = hl.plugin and hl.plugin.hy3
  if not (plugin and plugin.detach) then return end
  local win = hl.get_active_window and hl.get_active_window()
  if not win then return hl.dispatch(plugin.detach("toggle")) end
  -- Already floating: this is the reattach half of the toggle, keep the box.
  if win.floating then return hl.dispatch(plugin.detach("toggle")) end
  local cw, ch = win.size.x, win.size.y
  hl.dispatch(plugin.detach("toggle"))
  local dx, dy = math.floor(cw * (1 - DETACH_SCALE)), math.floor(ch * (1 - DETACH_SCALE))
  if dx > 0 and dy > 0 then
    hl.dispatch(hl.dsp.window.resize({ x = -dx, y = -dy, relative = true }))
  end
end

